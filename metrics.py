# Active sessions = distinct Streamlit sessions seen in the last 5 minutes
_sessions: dict[str, float] = {}
_sessions_lock = threading.Lock()

def record_session(session_id: str) -> None:
    with _sessions_lock:
        _sessions[session_id] = time.time()

def _active_sessions(window_s: int = 300) -> int:
    now = time.time()
    with _sessions_lock:
        for sid, last_seen in list(_sessions.items()):
            if now - last_seen > window_s:
                del _sessions[sid]
        return len(_sessions)

ACTIVE_SESSIONS = Gauge("caption_active_sessions", "Distinct browser sessions seen in the last 5 min")
ACTIVE_SESSIONS.set_function(_active_sessions)

